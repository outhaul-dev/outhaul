#!/usr/bin/env sh
# Outhaul remote installer. Served at https://outhaul.sh/install.
# Usage: curl -fsSL https://outhaul.sh/install | sh
# Runs under Debian's dash — keep it POSIX, no bashisms.
set -eu

OUTHAUL_REPO="${OUTHAUL_REPO:-https://github.com/outhaul-dev/outhaul.git}"

# The unattended interface sets these; the defaults keep today's wizard path.
NONINTERACTIVE=0
INSTALL_DOCKER=0

# nixpacks is pinned: one version, one archive per architecture, each with the
# SHA-256 GitHub publishes for that asset. NIXPACKS_REPLACE=1 (--nixpacks on)
# lets the unattended installer replace a different installed version.
NIXPACKS_VERSION=1.41.0
NIXPACKS_SHA256_AMD64=0f55de7874507b9cf7502113120bd96f2ab6979f78d10eaf2eb2ade9207b3af6
NIXPACKS_SHA256_ARM64=912bd02dd2bb6f9c3a9ed965fe8a68b4aa318dc7a2546e2eca6f2806a894ba39
NIXPACKS_PATH=/usr/local/bin/nixpacks
NIXPACKS_REPLACE=${NIXPACKS_REPLACE:-0}

# ------------------------------------------------------------------ helpers --

# Prints the concrete Go version to download (e.g. 1.26.4). Prefers the
# `toolchain goX.Y.Z` directive; falls back to the `go X.Y[.Z]` directive.
go_version_from_gomod() {
	f=${1:-go.mod}
	v=$(awk '/^toolchain[ \t]+go[0-9]/ { sub(/^go/,"",$2); print $2; exit }' "$f")
	[ -n "$v" ] || v=$(awk '/^go[ \t]+[0-9]/ { print $2; exit }' "$f")
	printf '%s\n' "$v"
}

# Pure: decide color level from explicit inputs (testable).
# 0=plain 1=16-color 2=256-color 3=truecolor
_color_level() { # no_color is_tty colorterm tput_colors
	[ -n "$1" ] && {
		echo 0
		return
	}
	[ "$2" != 1 ] && {
		echo 0
		return
	}
	case "$3" in *truecolor* | *24bit*)
		echo 3
		return
		;;
	esac
	if [ "${4:-0}" -ge 256 ]; then
		echo 2
	elif [ "${4:-0}" -ge 8 ]; then
		echo 1
	else echo 0; fi
}

# Gathers the real environment and calls _color_level.
detect_color_level() {
	tc=$(tput colors 2>/dev/null || echo 0)
	if [ -t 1 ]; then tty=1; else tty=0; fi
	_color_level "${NO_COLOR:-}" "$tty" "${COLORTERM:-}" "$tc"
}

# Prints the space-separated, sorted, de-duplicated port set to open.
# SSH (22) is ALWAYS included. Mode a adds 80/443, as does mode c with the
# local CA (HTTPS redirect needs :80 too). A non-empty git port is added.
derive_firewall_ports() { # mode gitport localca
	mode=$1
	gitport=${2:-}
	localca=${3:-0}
	set -- 22
	[ "$mode" = a ] && set -- "$@" 80 443
	[ "$mode" = c ] && [ "$localca" = 1 ] && set -- "$@" 80 443
	[ -n "$gitport" ] && set -- "$@" "$gitport"
	printf '%s\n' "$@" | sort -n -u | paste -sd' ' -
}

# Returns success (0) when total RAM+swap is below 2 GiB and a build
# swapfile should be offered. Inputs are in KiB (as /proc/meminfo reports).
need_swap() { # mem_kb swap_kb
	total=$((${1:-0} + ${2:-0}))
	[ "$total" -lt 2097152 ]
}

# Writes /etc/outhaul.env from wizard answers. Mode a includes the public
# URL + ACME email (enables HTTPS on first boot); other modes omit them.
# Comments go on their OWN line — systemd keeps an inline "# ..." as part of
# the value, which would corrupt e.g. the email.
write_env_file() { # dest mode url email sshaddr localca
	dest=$1 mode=$2 url=$3 email=$4 sshaddr=$5 localca=${6:-0}
	{
		printf '# Outhaul configuration — generated by the installer.\n'
		printf '# OUTHAUL_* overrides, one per line. Comments on their OWN line.\n'
		printf '# Edit, then: systemctl restart outhaul\n\n'
		if [ "$mode" = a ]; then
			printf 'OUTHAUL_PUBLIC_URL=%s\n' "$url"
			printf 'OUTHAUL_ACME_EMAIL=%s\n' "$email"
		fi
		if [ "$mode" = c ] && [ "$localca" = 1 ]; then
			printf 'OUTHAUL_LOCAL_CA=true\n'
		fi
		[ -n "$sshaddr" ] && printf 'OUTHAUL_SSH_ADDR=%s\n' "$sshaddr"
	} >"$dest"
	chmod 0600 "$dest"
}

# Maps the git-port answer to a port, or empty to disable push-to-deploy.
# The prompt defaults to 2222, so an empty answer can never mean "disable".
normalize_git_port() { # answer
	case "$1" in
	[Nn][Oo][Nn][Ee] | [Nn][Oo] | [Nn] | 0 | -) printf '\n' ;;
	'' | *[!0-9]*)
		printf '  ! %s is not a port number; using 2222\n' "$1" >&2
		printf '2222\n'
		;;
	*) if [ "$1" -le 65535 ]; then printf '%s\n' "$1"; else
		printf '  ! %s is not a port number; using 2222\n' "$1" >&2
		printf '2222\n'
	fi ;;
	esac
}

git_ssh_from_port() { # port, empty for none
	if [ -n "$1" ]; then printf ':%s\n' "$1"; else printf 'off\n'; fi
}

# outhaul serve refuses a public URL without a scheme; a bare host means
# HTTPS (it is asked for in the Let's Encrypt mode).
normalize_public_url() { # answer
	case "$1" in
	'' | http://* | https://*) printf '%s\n' "$1" ;;
	*) printf 'https://%s\n' "$1" ;;
	esac
}

# Where prompts are read from (see open_prompt_fd): the controlling terminal
# when there is one; else stdin, but only when this script was started from a
# file — under `curl | sh` stdin IS the script, and reading answers from it
# would eat the code; else nothing, so every prompt takes its safe default.
prompt_source() { # tty_openable(0/1) script_path
	if [ "$1" = 1 ]; then
		echo tty
	elif [ -n "$2" ] && [ -f "$2" ]; then
		echo stdin
	else
		echo null
	fi
}

# Probes /dev/tty in a subshell: `exec 3<>/dev/tty` on a headless run is a
# failed redirection on a special builtin, which exits a POSIX shell outright
# (dash, bash --posix, busybox) before any `||` fallback can run.
tty_openable() { (: <>/dev/tty) 2>/dev/null; }

# Opens fd 3 for BOTH prompt output and input. Under `curl | sh` stdin is the
# pipe and stderr may be redirected away, so prompts written to stderr can go
# unseen — routing them to the tty guarantees they land where the user is
# typing. Without a tty, answers come from stdin (script run from a file, e.g.
# `printf '3\n…' | sh bootstrap.sh`) or not at all (/dev/null: prompts read EOF
# and take their defaults). Writes to a read-only fd 3 fall back to stderr.
open_prompt_fd() { # script_path
	if tty_openable; then _t=1; else _t=0; fi
	case $(prompt_source "$_t" "$1") in
	tty) exec 3<>/dev/tty ;;
	stdin) exec 3<&0 ;;
	*) exec 3<>/dev/null ;;
	esac
}

# Yes/no prompt: written to the tty on fd 3 (stderr fallback), read from fd 3. $2 is the default ('y' or 'n').
ask_yes_no() { # prompt default
	_p=$1
	_d=$2
	if [ "$_d" = y ]; then _h='Y/n'; else _h='y/N'; fi
	printf '%s [%s] ' "$_p" "$_h" >&3 2>/dev/null || printf '%s [%s] ' "$_p" "$_h" >&2
	read _a <&3 2>/dev/null || _a=''
	[ -z "$_a" ] && _a=$_d
	case "$_a" in [Yy]*) return 0 ;; *) return 1 ;; esac
}

# Free-text prompt: written to the tty on fd 3 (stderr fallback), read from fd 3; prints the answer (or default) to stdout.
ask_value() { # prompt default
	_p=$1
	_d=$2
	if [ -n "$_d" ]; then _t="$_p [$_d] "; else _t="$_p "; fi
	printf '%s' "$_t" >&3 2>/dev/null || printf '%s' "$_t" >&2
	read _a <&3 2>/dev/null || _a=''
	[ -z "$_a" ] && _a=$_d
	printf '%s\n' "$_a"
}

# ------------------------------------------------------------------- ui --

# Sets COLOR, UNICODE, WIDTH globals. Call once at startup.
init_ui() {
	COLOR=$(detect_color_level)
	case "${LC_ALL:-${LC_CTYPE:-${LANG:-}}}" in *[Uu][Tt][Ff]-8* | *[Uu][Tt][Ff]8*) UNICODE=1 ;; *) UNICODE=0 ;; esac
	[ "$COLOR" = 0 ] && UNICODE=0
	WIDTH=$(tput cols 2>/dev/null || echo 80)
	[ -n "$WIDTH" ] || WIDTH=80
}

# Apply an RGB (truecolor) / bold-magenta (16+) / plain color to text.
paint() { # r g b text...
	_r=$1
	_g=$2
	_b=$3
	shift 3
	if [ "${COLOR:-0}" -ge 3 ]; then
		printf '\033[38;2;%d;%d;%dm%s\033[0m' "$_r" "$_g" "$_b" "$*"
	elif [ "${COLOR:-0}" -ge 1 ]; then
		printf '\033[1;35m%s\033[0m' "$*"
	else printf '%s' "$*"; fi
}

_c() { # color-code-or-plain: emit ANSI SGR $1 only when COLOR>=1
	[ "${COLOR:-0}" -ge 1 ] && printf '\033[%sm' "$1" || true
}

hr() {
	[ "${UNICODE:-0}" = 1 ] && ch='─' || ch='-'
	i=0
	line=''
	while [ "$i" -lt "$((WIDTH < 80 ? WIDTH : 60))" ]; do
		line="$line$ch"
		i=$((i + 1))
	done
	_c 90
	printf '%s' "$line"
	_c 0
	printf '\n'
}

step_ok() {
	[ "${UNICODE:-0}" = 1 ] && m='✔' || m='+'
	_c '1;32'
	printf '  %s ' "$m"
	_c 0
	printf '%s\n' "$1"
}
step_fail() {
	[ "${UNICODE:-0}" = 1 ] && m='✖' || m='x'
	_c '1;31'
	printf '  %s ' "$m"
	_c 0
	printf '%s\n' "$1"
}
note() {
	_c 90
	printf '    %s\n' "$1"
	_c 0
}

# Raw log mirror (Task 20 wires LOGFILE); safe if unset.
log_line() { [ -n "${LOGFILE:-}" ] && printf '%s\n' "$*" >>"$LOGFILE" 2>/dev/null || true; }

die() {
	_c '1;31'
	printf 'error: ' >&2
	_c 0
	printf '%s\n' "$1" >&2
	log_line "ERROR: $1"
	exit 1
}

_hero_rgb() { case $1 in
	1) echo 247 120 186 ;; 2) echo 188 140 255 ;;
	3) echo 88 166 255 ;; 4) echo 63 185 80 ;; esac }

# Gradient ASCII wordmark; degrades to a single line when narrow or plain.
hero() {
	if [ "${WIDTH:-80}" -lt 62 ]; then
		printf '\n'
		_c '1;35'
		printf '  Outhaul'
		_c 0
		printf ' — self-hosted PaaS\n\n'
		return
	fi
	printf '\n'
	set -- \
		'  ██████  ██    ██ ████████ ██   ██  █████  ██    ██ ██     ' \
		'  ██   ██ ██    ██    ██    ██   ██ ██   ██ ██    ██ ██     ' \
		'  ██   ██ ██    ██    ██    ███████ ███████ ██    ██ ██     ' \
		'  ██████   ██████     ██    ██   ██ ██   ██  ██████  ███████'
	i=0
	# shellcheck disable=SC2046 # intentional: _hero_rgb's 3 numbers become 3 args to paint
	for line in "$@"; do
		i=$((i + 1))
		paint $(_hero_rgb "$i") "$line"
		printf '\n'
	done
	_c 90
	printf '   self-hosted PaaS · one binary, zero sprawl\n'
	_c 0
	printf '\n'
}

# Braille spinner on a background PID while a long step runs.
# Usage: spinner_start "message"; <work>; spinner_stop 0|1
SPIN_PID=''
spinner_start() {
	SPIN_MSG=$1
	if [ "${COLOR:-0}" = 0 ] || [ ! -t 1 ]; then
		printf '  .. %s\n' "$SPIN_MSG"
		return
	fi
	(
		frames='⠋⠙⠹⠸⠼⠴⠦⠧⠇⠏'
		[ "${UNICODE:-0}" = 1 ] || frames='|/-\\'
		while :; do
			i=1
			while [ "$i" -le ${#frames} ]; do
				f=$(printf '%s' "$frames" | cut -c "$i")
				printf '\r  \033[35m%s\033[0m %s' "$f" "$SPIN_MSG"
				sleep 0.1
				i=$((i + 1))
			done
		done
	) &
	SPIN_PID=$!
}
spinner_stop() { # exitcode
	[ -n "${SPIN_PID:-}" ] && kill "$SPIN_PID" 2>/dev/null && wait "$SPIN_PID" 2>/dev/null
	SPIN_PID=''
	[ "${COLOR:-0}" = 0 ] && return 0
	printf '\r\033[K'
	if [ "${1:-0}" -eq 0 ]; then step_ok "$SPIN_MSG"; else step_fail "$SPIN_MSG"; fi
}

# A single-line gradient progress bar: progress_bar PERCENT LABEL
progress_bar() { # percent label
	pct=$1
	label=${2:-}
	width=30
	filled=$((pct * width / 100))
	[ "$filled" -gt "$width" ] && filled=$width
	bar=''
	i=0
	while [ "$i" -lt "$filled" ]; do
		bar="$bar#"
		i=$((i + 1))
	done
	while [ "$i" -lt "$width" ]; do
		bar="$bar."
		i=$((i + 1))
	done
	if [ "${COLOR:-0}" -ge 1 ]; then
		printf '\r  \033[32m%s\033[0m %3d%% %s' "$bar" "$pct" "$label"
	else
		printf '\r  %s %3d%% %s' "$bar" "$pct" "$label"
	fi
}

# ------------------------------------------------------------------ system --

# Prints the numeric KiB value for a /proc/meminfo key (default file /proc/meminfo).
read_meminfo_kb() { # key file?
	awk -v k="$1:" '$1==k {print $2; exit}' "${2:-/proc/meminfo}"
}

# Prints the distro ID from an os-release file (default /etc/os-release).
# shellcheck disable=SC2120  # the file arg is only passed by the tests
detect_distro() { # file?
	awk -F= '$1=="ID"{gsub(/"/,"",$2); print $2; exit}' "${1:-/etc/os-release}"
}

# True for the distros the installer is tested on. Both use apt, ufw,
# systemd and get.docker.com, so the rest of the script is the same.
distro_supported() { # id
	case "$1" in debian | ubuntu) return 0 ;; *) return 1 ;; esac
}

# Full preflight. Aborts on hard failures; warns (via fd 3 confirm) on soft ones.
preflight() {
	[ "$(id -u)" -eq 0 ] || die "run as root (curl -fsSL https://outhaul.sh/install | sudo sh)"
	command -v systemctl >/dev/null 2>&1 || die "systemd is required (no systemctl found)"
	distro=$(detect_distro)
	if distro_supported "$distro"; then
		step_ok "$distro detected"
	else
		step_fail "unsupported distro: ${distro:-unknown} (V1 targets Debian and Ubuntu)"
		ask_yes_no "  Continue anyway?" n || die "aborted on unsupported distro"
	fi
	arch=$(uname -m)
	case "$arch" in x86_64 | amd64 | aarch64 | arm64) step_ok "architecture $arch" ;;
	*) die "unsupported architecture: $arch" ;; esac
	MEM_KB=$(read_meminfo_kb MemTotal)
	SWAP_KB=$(read_meminfo_kb SwapTotal)
	note "memory: $((MEM_KB / 1024)) MB RAM, $((SWAP_KB / 1024)) MB swap"
}

have_docker() { command -v docker >/dev/null 2>&1; }
have_docker_service() { systemctl cat docker.service >/dev/null 2>&1; }
have_docker_socket() { [ -e /var/run/docker.sock ]; }

# True when an installed Docker answers and has compose v2. The daemon may
# still be starting (first boot, or just after the install), so wait 30s.
docker_works() {
	have_docker || return 1
	_i=0
	while [ "$_i" -lt 30 ]; do
		if docker version --format '{{.Server.Version}}' >/dev/null 2>&1 &&
			docker compose version >/dev/null 2>&1; then
			return 0
		fi
		sleep 1
		_i=$((_i + 1))
	done
	return 1
}

# Prints what is wrong with a Docker that is present but not working.
docker_problem() {
	if ! docker version --format '{{.Server.Version}}' >/dev/null 2>&1; then
		printf '%s\n' "the Docker daemon is not answering"
	else
		printf '%s\n' "the docker compose v2 plugin is missing"
	fi
}

# Three states: a working Docker is used as it is; an absent one is installed
# only when allowed; one that is present but broken is started once and then
# reported — get.docker.com never runs over it.
ensure_docker() {
	if docker_works; then
		step_ok "Docker is working"
		return
	fi
	if ! have_docker && ! have_docker_service && ! have_docker_socket; then
		if [ "$NONINTERACTIVE" = 1 ] && [ "$INSTALL_DOCKER" != 1 ]; then
			die "Docker is not installed; install it first or pass --install-docker"
		fi
		spinner_start "installing Docker (get.docker.com)"
		# set +e so a failed install still reaches spinner_stop + die (see build_binary note).
		set +e
		curl -fsSL https://get.docker.com | sh >>"${LOGFILE:-/dev/null}" 2>&1
		rc=$?
		set -e
		spinner_stop "$rc"
		[ "$rc" -eq 0 ] || die "Docker install failed — see ${LOGFILE:-the install log}"
	fi
	# Present but not answering: start the daemon once. Never reinstall.
	systemctl enable --now docker >/dev/null 2>&1 || true
	if docker_works; then
		step_ok "Docker is working"
		return
	fi
	die "$(docker_problem)"
}

ensure_git() {
	if command -v git >/dev/null 2>&1; then
		step_ok "git present"
		return
	fi
	spinner_start "installing git"
	set +e
	{ apt-get update -qq && apt-get install -y -qq git; } >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	[ "$rc" -eq 0 ] || die "git install failed — see ${LOGFILE:-the install log}"
}

# Maps uname -m to the nixpacks release asset's target triple.
nixpacks_target() { # uname_m
	case "$1" in
	x86_64 | amd64) echo x86_64-unknown-linux-musl ;;
	aarch64 | arm64) echo aarch64-unknown-linux-musl ;;
	*) return 1 ;;
	esac
}

# Prints the pinned SHA-256 for the host's architecture.
nixpacks_sha256() { # uname_m
	case "$1" in
	x86_64 | amd64) printf '%s\n' "$NIXPACKS_SHA256_AMD64" ;;
	aarch64 | arm64) printf '%s\n' "$NIXPACKS_SHA256_ARM64" ;;
	*) return 1 ;;
	esac
}

# Prints the installed nixpacks version, or nothing when there is none.
nixpacks_installed_version() {
	command -v nixpacks >/dev/null 2>&1 || return 0
	nixpacks --version 2>/dev/null | awk '{print $NF}'
}

# Downloads the pinned archive, verifies its checksum and installs the binary
# by rename. A wrong checksum is fatal in every mode: the host asked for the
# pin, and something other than it arrived.
install_nixpacks_pin() {
	arch=$(uname -m)
	target=$(nixpacks_target "$arch") || die "unsupported architecture for nixpacks: $arch"
	sum=$(nixpacks_sha256 "$arch") || die "unsupported architecture for nixpacks: $arch"
	NIXPACKS_TMP=$(mktemp -d)
	archive=$NIXPACKS_TMP/nixpacks.tar.gz
	url="https://github.com/railwayapp/nixpacks/releases/download/v$NIXPACKS_VERSION/nixpacks-v$NIXPACKS_VERSION-$target.tar.gz"
	spinner_start "downloading nixpacks $NIXPACKS_VERSION ($target)"
	set +e
	curl -fsSL "$url" -o "$archive" >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	if [ "$rc" -ne 0 ]; then
		rm -rf "$NIXPACKS_TMP"
		NIXPACKS_TMP=''
		if [ "$NONINTERACTIVE" = 1 ]; then
			die "could not download nixpacks $NIXPACKS_VERSION from $url"
		fi
		note "could not download nixpacks $NIXPACKS_VERSION — you can retry later; Dockerfile/compose apps work without it"
		return 0
	fi
	if ! echo "$sum  $archive" | sha256sum -c - >>"${LOGFILE:-/dev/null}" 2>&1; then
		rm -rf "$NIXPACKS_TMP"
		NIXPACKS_TMP=''
		die "nixpacks checksum mismatch — refusing to install"
	fi
	step_ok "nixpacks $NIXPACKS_VERSION checksum verified"
	if ! tar -C "$NIXPACKS_TMP" -xzf "$archive"; then
		rm -rf "$NIXPACKS_TMP"
		NIXPACKS_TMP=''
		die "could not extract nixpacks $NIXPACKS_VERSION"
	fi
	if ! install_atomic "$NIXPACKS_TMP/nixpacks" "$NIXPACKS_PATH" 0755; then
		rm -rf "$NIXPACKS_TMP"
		NIXPACKS_TMP=''
		die "could not install nixpacks to $NIXPACKS_PATH"
	fi
	rm -rf "$NIXPACKS_TMP"
	NIXPACKS_TMP=''
	step_ok "installed nixpacks $NIXPACKS_VERSION"
}

# Optional — caller gates on WANT_NIXPACKS. A version other than the pin is
# left alone unless NIXPACKS_REPLACE=1: replacing a working build tool is the
# operator's call, not the installer's.
ensure_nixpacks() {
	v=$(nixpacks_installed_version)
	if [ -z "$v" ]; then
		install_nixpacks_pin
		return
	fi
	if [ "$v" = "$NIXPACKS_VERSION" ]; then
		step_ok "nixpacks $NIXPACKS_VERSION present"
		return
	fi
	if [ "$NIXPACKS_REPLACE" = 1 ]; then
		install_nixpacks_pin
		return
	fi
	note "nixpacks $v is installed; the installer pins $NIXPACKS_VERSION (re-run with --non-interactive --nixpacks on to replace it)"
}

# Pure: true only for a bare 64-char hex sha256 digest. Guards against a checksum
# endpoint answering 200 with an HTML stub, which would otherwise surface as a
# confusing "checksum mismatch" instead of "the sidecar was not a digest".
is_sha256() { # candidate
	case "$1" in
	'' | *[!0-9a-fA-F]*) return 1 ;;
	esac
	[ "${#1}" -eq 64 ]
}

# Maps uname -m to the go.dev download arch token.
go_dl_arch() { # uname_m
	case "$1" in
	x86_64 | amd64) echo amd64 ;;
	aarch64 | arm64) echo arm64 ;;
	*) return 1 ;;
	esac
}

# Downloads the go.mod-pinned Go toolchain to a temp dir, verifies its SHA256
# against the value published in the accompanying .sha256, and exports PATH.
# Sets GOROOT_TMP so the caller can remove it later.
install_go_toolchain() { # version
	ver=$1
	if command -v go >/dev/null 2>&1 && [ "$(go env GOVERSION 2>/dev/null)" = "go$ver" ]; then
		step_ok "Go $ver present"
		return
	fi
	a=$(go_dl_arch "$(uname -m)") || die "unsupported arch for Go download"
	GOROOT_TMP=$(mktemp -d)
	tarball="go${ver}.linux-${a}.tar.gz"
	# dl.google.com is the canonical artifact host and serves the .sha256 sidecar as
	# a raw 64-char digest. Do NOT use go.dev/dl/<file>.sha256: it answers 200 with an
	# HTML redirect stub, which silently poisons $sum and fails verification.
	url="https://dl.google.com/go/${tarball}"
	spinner_start "downloading Go $ver ($a)"
	set +e
	{
		curl -fsSL "$url" -o "$GOROOT_TMP/$tarball" &&
			curl -fsSL "$url.sha256" -o "$GOROOT_TMP/$tarball.sha256"
	} >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	[ "$rc" -eq 0 ] || die "could not download Go $ver from $url"
	sum=$(tr -d '[:space:]' <"$GOROOT_TMP/$tarball.sha256")
	is_sha256 "$sum" || die "bad checksum file from $url.sha256 — not a sha256 digest (got ${#sum} chars)"
	echo "$sum  $GOROOT_TMP/$tarball" | sha256sum -c - >>"${LOGFILE:-/dev/null}" 2>&1 ||
		die "Go toolchain checksum mismatch — refusing to build"
	step_ok "Go $ver checksum verified"
	tar -C "$GOROOT_TMP" -xzf "$GOROOT_TMP/$tarball"
	PATH="$GOROOT_TMP/go/bin:$PATH"
	export PATH
	GOTOOLCHAIN=local
	export GOTOOLCHAIN # do not let go fetch a different one
	step_ok "Go $ver ready"
}

BUILD_SWAP=/var/lib/outhaul-build.swap

# Offers a temporary build swapfile when RAM+swap is under 2 GiB.
maybe_add_swap() { # mem_kb swap_kb
	need_swap "$1" "$2" || return 0
	note "low memory — the Go build may be OOM-killed without extra swap"
	ask_yes_no "  Create a temporary 2 GB swapfile for the build?" y || return 0
	[ -e "$BUILD_SWAP" ] && return 0
	spinner_start "creating build swapfile"
	# Mark now so cleanup removes the file even if swapon fails partway through.
	SWAP_ADDED=1
	set +e
	{
		fallocate -l 2G "$BUILD_SWAP" 2>/dev/null || dd if=/dev/zero of="$BUILD_SWAP" bs=1M count=2048
		chmod 600 "$BUILD_SWAP" && mkswap "$BUILD_SWAP" && swapon "$BUILD_SWAP"
	} >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	# Not fatal: continue even if swap couldn't be enabled (the build may just be tight).
	[ "$rc" -eq 0 ] || note "could not enable build swap — continuing without it"
}

# Removes only the swapfile we created.
remove_build_swap() {
	[ "${SWAP_ADDED:-0}" = 1 ] || return 0
	swapoff "$BUILD_SWAP" 2>/dev/null || true
	rm -f "$BUILD_SWAP"
	SWAP_ADDED=0
}

# Clones the repo (or uses --from-checkout dir) and checks out target, a full
# commit. Prints the source dir via SRC_DIR. With no argument it resolves the
# remote's HEAD first: the updater calls it that way.
fetch_source() { # [target]
	if [ "${FROM_CHECKOUT:-0}" = 1 ]; then
		SRC_DIR=$(cd "$CHECKOUT_DIR" && pwd)
		[ -f "$SRC_DIR/go.mod" ] || die "--from-checkout: no go.mod in $SRC_DIR"
		step_ok "using local checkout $SRC_DIR"
		return
	fi
	_target=${1:-}
	if [ -z "$_target" ]; then
		resolve_ref '' "$OUTHAUL_REPO"
		_target=$TARGET
	fi
	SRC_DIR=$(mktemp -d)
	_log=${LOGFILE:-/dev/null}
	# The tests call this before main has opened the install log; a log that
	# cannot be opened is no reason to fail the fetch.
	(: >>"$_log") 2>/dev/null || _log=/dev/null
	spinner_start "fetching outhaul $(short "$_target")"
	set +e
	{
		git init -q "$SRC_DIR" &&
			git -C "$SRC_DIR" fetch --depth 1 "$OUTHAUL_REPO" "$_target" &&
			git -C "$SRC_DIR" checkout --detach FETCH_HEAD
	} >>"$_log" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	[ "$rc" -eq 0 ] || die "could not fetch $(short "$_target") from $OUTHAUL_REPO — see ${LOGFILE:-the install log}"
	_fetched=$(git -C "$SRC_DIR" rev-parse HEAD 2>/dev/null || true)
	[ "$_fetched" = "$_target" ] || die "fetched $_fetched, not $_target"
}

# Resolves ref (a tag, a branch, a full commit, or nothing for the remote's
# HEAD) to TARGET, a full commit. A tag's name becomes TARGET_VERSION; a
# branch or a commit leaves it empty. TARGET_REF is the ref as it was given.
resolve_ref() { # ref repo
	_ref=$1 _repo=$2
	TARGET_VERSION=''
	if [ -z "$_ref" ]; then
		TARGET_REF=HEAD
		TARGET=$(git ls-remote "$_repo" HEAD 2>/dev/null | awk 'NR == 1 { print $1 }')
		[ -n "$TARGET" ] || die "could not resolve HEAD of $_repo"
		return 0
	fi
	TARGET_REF=$_ref
	case "$_ref" in
	*[!0-9a-fA-F]*) ;;
	*)
		if [ "${#_ref}" -eq 40 ]; then
			TARGET=$(printf '%s\n' "$_ref" | tr 'A-F' 'a-f')
			return 0
		fi
		if [ "${#_ref}" -ge 7 ]; then
			die "a shortened commit cannot be fetched; give the full 40 characters"
		fi
		;;
	esac
	_refs=$(git ls-remote "$_repo" 2>/dev/null) || die "could not read the refs of $_repo"
	# ^{} is an annotated tag's peeled commit: fetch that, not the tag object.
	TARGET=$(printf '%s\n' "$_refs" | awk -v r="refs/tags/$_ref^{}" '$2 == r { print $1; exit }')
	if [ -z "$TARGET" ]; then
		TARGET=$(printf '%s\n' "$_refs" | awk -v r="refs/tags/$_ref" '$2 == r { print $1; exit }')
	fi
	if [ -n "$TARGET" ]; then
		TARGET_VERSION=$_ref
		return 0
	fi
	TARGET=$(printf '%s\n' "$_refs" | awk -v r="refs/heads/$_ref" '$2 == r { print $1; exit }')
	[ -n "$TARGET" ] || die "no tag or branch named $_ref in $_repo; give a full 40-character commit"
}

