#!/usr/bin/env sh
# Outhaul remote installer. Served at https://outhaul.sh/install.
# Usage: curl -fsSL https://outhaul.sh/install | sh
# Runs under Debian's dash — keep it POSIX, no bashisms.
set -eu

OUTHAUL_REPO="${OUTHAUL_REPO:-https://github.com/outhaul-dev/outhaul.git}"

# ------------------------------------------------------------------ helpers --

# Prints the concrete Go version to download (e.g. 1.26.4). Prefers the
# `toolchain goX.Y.Z` directive; falls back to the `go X.Y[.Z]` directive.
go_version_from_gomod() {
	f=${1:-go.mod}
	v=$(awk '/^toolchain[ \t]+go[0-9]/ { sub(/^go/,"",$2); print $2; exit }' "$f")
	[ -n "$v" ] || v=$(awk '/^go[ \t]+[0-9]/ { print $2; exit }' "$f")
	printf '%s\n' "$v"
}

# Pure: decide color level from explicit inputs (testable).
# 0=plain 1=16-color 2=256-color 3=truecolor
_color_level() { # no_color is_tty colorterm tput_colors
	[ -n "$1" ] && {
		echo 0
		return
	}
	[ "$2" != 1 ] && {
		echo 0
		return
	}
	case "$3" in *truecolor* | *24bit*)
		echo 3
		return
		;;
	esac
	if [ "${4:-0}" -ge 256 ]; then
		echo 2
	elif [ "${4:-0}" -ge 8 ]; then
		echo 1
	else echo 0; fi
}

# Gathers the real environment and calls _color_level.
detect_color_level() {
	tc=$(tput colors 2>/dev/null || echo 0)
	if [ -t 1 ]; then tty=1; else tty=0; fi
	_color_level "${NO_COLOR:-}" "$tty" "${COLORTERM:-}" "$tc"
}

# Prints the space-separated, sorted, de-duplicated port set to open.
# SSH (22) is ALWAYS included. Mode a adds 80/443, as does mode c with the
# local CA (HTTPS redirect needs :80 too). A non-empty git port is added.
derive_firewall_ports() { # mode gitport localca
	mode=$1
	gitport=${2:-}
	localca=${3:-0}
	set -- 22
	[ "$mode" = a ] && set -- "$@" 80 443
	[ "$mode" = c ] && [ "$localca" = 1 ] && set -- "$@" 80 443
	[ -n "$gitport" ] && set -- "$@" "$gitport"
	printf '%s\n' "$@" | sort -n -u | paste -sd' ' -
}

# Returns success (0) when total RAM+swap is below 2 GiB and a build
# swapfile should be offered. Inputs are in KiB (as /proc/meminfo reports).
need_swap() { # mem_kb swap_kb
	total=$((${1:-0} + ${2:-0}))
	[ "$total" -lt 2097152 ]
}

# Writes /etc/outhaul.env from wizard answers. Mode a includes the public
# URL + ACME email (enables HTTPS on first boot); other modes omit them.
# Comments go on their OWN line — systemd keeps an inline "# ..." as part of
# the value, which would corrupt e.g. the email.
write_env_file() { # dest mode url email sshaddr localca
	dest=$1 mode=$2 url=$3 email=$4 sshaddr=$5 localca=${6:-0}
	{
		printf '# Outhaul configuration — generated by the installer.\n'
		printf '# OUTHAUL_* overrides, one per line. Comments on their OWN line.\n'
		printf '# Edit, then: systemctl restart outhaul\n\n'
		if [ "$mode" = a ]; then
			printf 'OUTHAUL_PUBLIC_URL=%s\n' "$url"
			printf 'OUTHAUL_ACME_EMAIL=%s\n' "$email"
		fi
		if [ "$mode" = c ] && [ "$localca" = 1 ]; then
			printf 'OUTHAUL_LOCAL_CA=true\n'
		fi
		[ -n "$sshaddr" ] && printf 'OUTHAUL_SSH_ADDR=%s\n' "$sshaddr"
	} >"$dest"
	chmod 0600 "$dest"
}

# Maps the git-port answer to a port, or empty to disable push-to-deploy.
# The prompt defaults to 2222, so an empty answer can never mean "disable".
normalize_git_port() { # answer
	case "$1" in
	[Nn][Oo][Nn][Ee] | [Nn][Oo] | [Nn] | 0 | -) printf '\n' ;;
	'' | *[!0-9]*)
		printf '  ! %s is not a port number; using 2222\n' "$1" >&2
		printf '2222\n'
		;;
	*) if [ "$1" -le 65535 ]; then printf '%s\n' "$1"; else
		printf '  ! %s is not a port number; using 2222\n' "$1" >&2
		printf '2222\n'
	fi ;;
	esac
}

# outhaul serve refuses a public URL without a scheme; a bare host means
# HTTPS (it is asked for in the Let's Encrypt mode).
normalize_public_url() { # answer
	case "$1" in
	'' | http://* | https://*) printf '%s\n' "$1" ;;
	*) printf 'https://%s\n' "$1" ;;
	esac
}

# Where prompts are read from (see open_prompt_fd): the controlling terminal
# when there is one; else stdin, but only when this script was started from a
# file — under `curl | sh` stdin IS the script, and reading answers from it
# would eat the code; else nothing, so every prompt takes its safe default.
prompt_source() { # tty_openable(0/1) script_path
	if [ "$1" = 1 ]; then
		echo tty
	elif [ -n "$2" ] && [ -f "$2" ]; then
		echo stdin
	else
		echo null
	fi
}

# Probes /dev/tty in a subshell: `exec 3<>/dev/tty` on a headless run is a
# failed redirection on a special builtin, which exits a POSIX shell outright
# (dash, bash --posix, busybox) before any `||` fallback can run.
tty_openable() { (: <>/dev/tty) 2>/dev/null; }

# Opens fd 3 for BOTH prompt output and input. Under `curl | sh` stdin is the
# pipe and stderr may be redirected away, so prompts written to stderr can go
# unseen — routing them to the tty guarantees they land where the user is
# typing. Without a tty, answers come from stdin (script run from a file, e.g.
# `printf '3\n…' | sh bootstrap.sh`) or not at all (/dev/null: prompts read EOF
# and take their defaults). Writes to a read-only fd 3 fall back to stderr.
open_prompt_fd() { # script_path
	if tty_openable; then _t=1; else _t=0; fi
	case $(prompt_source "$_t" "$1") in
	tty) exec 3<>/dev/tty ;;
	stdin) exec 3<&0 ;;
	*) exec 3<>/dev/null ;;
	esac
}

# Yes/no prompt: written to the tty on fd 3 (stderr fallback), read from fd 3. $2 is the default ('y' or 'n').
ask_yes_no() { # prompt default
	_p=$1
	_d=$2
	if [ "$_d" = y ]; then _h='Y/n'; else _h='y/N'; fi
	printf '%s [%s] ' "$_p" "$_h" >&3 2>/dev/null || printf '%s [%s] ' "$_p" "$_h" >&2
	read _a <&3 2>/dev/null || _a=''
	[ -z "$_a" ] && _a=$_d
	case "$_a" in [Yy]*) return 0 ;; *) return 1 ;; esac
}

# Free-text prompt: written to the tty on fd 3 (stderr fallback), read from fd 3; prints the answer (or default) to stdout.
ask_value() { # prompt default
	_p=$1
	_d=$2
	if [ -n "$_d" ]; then _t="$_p [$_d] "; else _t="$_p "; fi
	printf '%s' "$_t" >&3 2>/dev/null || printf '%s' "$_t" >&2
	read _a <&3 2>/dev/null || _a=''
	[ -z "$_a" ] && _a=$_d
	printf '%s\n' "$_a"
}

# ------------------------------------------------------------------- ui --

# Sets COLOR, UNICODE, WIDTH globals. Call once at startup.
init_ui() {
	COLOR=$(detect_color_level)
	case "${LC_ALL:-${LC_CTYPE:-${LANG:-}}}" in *[Uu][Tt][Ff]-8* | *[Uu][Tt][Ff]8*) UNICODE=1 ;; *) UNICODE=0 ;; esac
	[ "$COLOR" = 0 ] && UNICODE=0
	WIDTH=$(tput cols 2>/dev/null || echo 80)
	[ -n "$WIDTH" ] || WIDTH=80
}

# Apply an RGB (truecolor) / bold-magenta (16+) / plain color to text.
paint() { # r g b text...
	_r=$1
	_g=$2
	_b=$3
	shift 3
	if [ "${COLOR:-0}" -ge 3 ]; then
		printf '\033[38;2;%d;%d;%dm%s\033[0m' "$_r" "$_g" "$_b" "$*"
	elif [ "${COLOR:-0}" -ge 1 ]; then
		printf '\033[1;35m%s\033[0m' "$*"
	else printf '%s' "$*"; fi
}

_c() { # color-code-or-plain: emit ANSI SGR $1 only when COLOR>=1
	[ "${COLOR:-0}" -ge 1 ] && printf '\033[%sm' "$1" || true
}

hr() {
	[ "${UNICODE:-0}" = 1 ] && ch='─' || ch='-'
	i=0
	line=''
	while [ "$i" -lt "$((WIDTH < 80 ? WIDTH : 60))" ]; do
		line="$line$ch"
		i=$((i + 1))
	done
	_c 90
	printf '%s' "$line"
	_c 0
	printf '\n'
}

step_ok() {
	[ "${UNICODE:-0}" = 1 ] && m='✔' || m='+'
	_c '1;32'
	printf '  %s ' "$m"
	_c 0
	printf '%s\n' "$1"
}
step_fail() {
	[ "${UNICODE:-0}" = 1 ] && m='✖' || m='x'
	_c '1;31'
	printf '  %s ' "$m"
	_c 0
	printf '%s\n' "$1"
}
note() {
	_c 90
	printf '    %s\n' "$1"
	_c 0
}

# Raw log mirror (Task 20 wires LOGFILE); safe if unset.
log_line() { [ -n "${LOGFILE:-}" ] && printf '%s\n' "$*" >>"$LOGFILE" 2>/dev/null || true; }

die() {
	_c '1;31'
	printf 'error: ' >&2
	_c 0
	printf '%s\n' "$1" >&2
	log_line "ERROR: $1"
	exit 1
}

_hero_rgb() { case $1 in
	1) echo 247 120 186 ;; 2) echo 188 140 255 ;;
	3) echo 88 166 255 ;; 4) echo 63 185 80 ;; esac }

# Gradient ASCII wordmark; degrades to a single line when narrow or plain.
hero() {
	if [ "${WIDTH:-80}" -lt 62 ]; then
		printf '\n'
		_c '1;35'
		printf '  Outhaul'
		_c 0
		printf ' — self-hosted PaaS\n\n'
		return
	fi
	printf '\n'
	set -- \
		'  ██████  ██    ██ ████████ ██   ██  █████  ██    ██ ██     ' \
		'  ██   ██ ██    ██    ██    ██   ██ ██   ██ ██    ██ ██     ' \
		'  ██   ██ ██    ██    ██    ███████ ███████ ██    ██ ██     ' \
		'  ██████   ██████     ██    ██   ██ ██   ██  ██████  ███████'
	i=0
	# shellcheck disable=SC2046 # intentional: _hero_rgb's 3 numbers become 3 args to paint
	for line in "$@"; do
		i=$((i + 1))
		paint $(_hero_rgb "$i") "$line"
		printf '\n'
	done
	_c 90
	printf '   self-hosted PaaS · one binary, zero sprawl\n'
	_c 0
	printf '\n'
}

# Braille spinner on a background PID while a long step runs.
# Usage: spinner_start "message"; <work>; spinner_stop 0|1
SPIN_PID=''
spinner_start() {
	SPIN_MSG=$1
	if [ "${COLOR:-0}" = 0 ] || [ ! -t 1 ]; then
		printf '  .. %s\n' "$SPIN_MSG"
		return
	fi
	(
		frames='⠋⠙⠹⠸⠼⠴⠦⠧⠇⠏'
		[ "${UNICODE:-0}" = 1 ] || frames='|/-\\'
		while :; do
			i=1
			while [ "$i" -le ${#frames} ]; do
				f=$(printf '%s' "$frames" | cut -c "$i")
				printf '\r  \033[35m%s\033[0m %s' "$f" "$SPIN_MSG"
				sleep 0.1
				i=$((i + 1))
			done
		done
	) &
	SPIN_PID=$!
}
spinner_stop() { # exitcode
	[ -n "${SPIN_PID:-}" ] && kill "$SPIN_PID" 2>/dev/null && wait "$SPIN_PID" 2>/dev/null
	SPIN_PID=''
	[ "${COLOR:-0}" = 0 ] && return 0
	printf '\r\033[K'
	if [ "${1:-0}" -eq 0 ]; then step_ok "$SPIN_MSG"; else step_fail "$SPIN_MSG"; fi
}

# A single-line gradient progress bar: progress_bar PERCENT LABEL
progress_bar() { # percent label
	pct=$1
	label=${2:-}
	width=30
	filled=$((pct * width / 100))
	[ "$filled" -gt "$width" ] && filled=$width
	bar=''
	i=0
	while [ "$i" -lt "$filled" ]; do
		bar="$bar#"
		i=$((i + 1))
	done
	while [ "$i" -lt "$width" ]; do
		bar="$bar."
		i=$((i + 1))
	done
	if [ "${COLOR:-0}" -ge 1 ]; then
		printf '\r  \033[32m%s\033[0m %3d%% %s' "$bar" "$pct" "$label"
	else
		printf '\r  %s %3d%% %s' "$bar" "$pct" "$label"
	fi
}

# ------------------------------------------------------------------ system --

# Prints the numeric KiB value for a /proc/meminfo key (default file /proc/meminfo).
read_meminfo_kb() { # key file?
	awk -v k="$1:" '$1==k {print $2; exit}' "${2:-/proc/meminfo}"
}

# Prints the distro ID from an os-release file (default /etc/os-release).
# shellcheck disable=SC2120  # the file arg is only passed by the tests
detect_distro() { # file?
	awk -F= '$1=="ID"{gsub(/"/,"",$2); print $2; exit}' "${1:-/etc/os-release}"
}

# True for the distros the installer is tested on. Both use apt, ufw,
# systemd and get.docker.com, so the rest of the script is the same.
distro_supported() { # id
	case "$1" in debian | ubuntu) return 0 ;; *) return 1 ;; esac
}

# Full preflight. Aborts on hard failures; warns (via fd 3 confirm) on soft ones.
preflight() {
	[ "$(id -u)" -eq 0 ] || die "run as root (curl -fsSL https://outhaul.sh/install | sudo sh)"
	command -v systemctl >/dev/null 2>&1 || die "systemd is required (no systemctl found)"
	distro=$(detect_distro)
	if distro_supported "$distro"; then
		step_ok "$distro detected"
	else
		step_fail "unsupported distro: ${distro:-unknown} (V1 targets Debian and Ubuntu)"
		ask_yes_no "  Continue anyway?" n || die "aborted on unsupported distro"
	fi
	arch=$(uname -m)
	case "$arch" in x86_64 | amd64 | aarch64 | arm64) step_ok "architecture $arch" ;;
	*) die "unsupported architecture: $arch" ;; esac
	MEM_KB=$(read_meminfo_kb MemTotal)
	SWAP_KB=$(read_meminfo_kb SwapTotal)
	note "memory: $((MEM_KB / 1024)) MB RAM, $((SWAP_KB / 1024)) MB swap"
}

ensure_docker() {
	if command -v docker >/dev/null 2>&1; then step_ok "Docker present"; else
		spinner_start "installing Docker (get.docker.com)"
		# set +e so a failed install still reaches spinner_stop + die (see build_binary note).
		set +e
		curl -fsSL https://get.docker.com | sh >>"${LOGFILE:-/dev/null}" 2>&1
		rc=$?
		set -e
		spinner_stop "$rc"
		[ "$rc" -eq 0 ] || die "Docker install failed — see ${LOGFILE:-the install log}"
	fi
	systemctl enable --now docker >/dev/null 2>&1 || true
	docker compose version >/dev/null 2>&1 || die "docker compose v2 plugin missing (install docker-compose-plugin)"
	step_ok "docker compose v2 available"
}

ensure_git() {
	if command -v git >/dev/null 2>&1; then
		step_ok "git present"
		return
	fi
	spinner_start "installing git"
	set +e
	{ apt-get update -qq && apt-get install -y -qq git; } >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	[ "$rc" -eq 0 ] || die "git install failed — see ${LOGFILE:-the install log}"
}

# Optional — caller gates on ask_yes_no.
ensure_nixpacks() {
	if command -v nixpacks >/dev/null 2>&1; then
		step_ok "nixpacks present"
		return
	fi
	spinner_start "installing nixpacks"
	set +e
	curl -fsSL https://nixpacks.com/install.sh | bash >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	# Optional: a failure is not fatal — Dockerfile/compose apps still deploy.
	[ "$rc" -eq 0 ] || note "nixpacks install failed — you can retry later; Dockerfile/compose apps work without it"
}

# Pure: true only for a bare 64-char hex sha256 digest. Guards against a checksum
# endpoint answering 200 with an HTML stub, which would otherwise surface as a
# confusing "checksum mismatch" instead of "the sidecar was not a digest".
is_sha256() { # candidate
	case "$1" in
	'' | *[!0-9a-fA-F]*) return 1 ;;
	esac
	[ "${#1}" -eq 64 ]
}

# Maps uname -m to the go.dev download arch token.
go_dl_arch() { # uname_m
	case "$1" in
	x86_64 | amd64) echo amd64 ;;
	aarch64 | arm64) echo arm64 ;;
	*) return 1 ;;
	esac
}

# Downloads the go.mod-pinned Go toolchain to a temp dir, verifies its SHA256
# against the value published in the accompanying .sha256, and exports PATH.
# Sets GOROOT_TMP so the caller can remove it later.
install_go_toolchain() { # version
	ver=$1
	if command -v go >/dev/null 2>&1 && [ "$(go env GOVERSION 2>/dev/null)" = "go$ver" ]; then
		step_ok "Go $ver present"
		return
	fi
	a=$(go_dl_arch "$(uname -m)") || die "unsupported arch for Go download"
	GOROOT_TMP=$(mktemp -d)
	tarball="go${ver}.linux-${a}.tar.gz"
	# dl.google.com is the canonical artifact host and serves the .sha256 sidecar as
	# a raw 64-char digest. Do NOT use go.dev/dl/<file>.sha256: it answers 200 with an
	# HTML redirect stub, which silently poisons $sum and fails verification.
	url="https://dl.google.com/go/${tarball}"
	spinner_start "downloading Go $ver ($a)"
	set +e
	{
		curl -fsSL "$url" -o "$GOROOT_TMP/$tarball" &&
			curl -fsSL "$url.sha256" -o "$GOROOT_TMP/$tarball.sha256"
	} >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	[ "$rc" -eq 0 ] || die "could not download Go $ver from $url"
	sum=$(tr -d '[:space:]' <"$GOROOT_TMP/$tarball.sha256")
	is_sha256 "$sum" || die "bad checksum file from $url.sha256 — not a sha256 digest (got ${#sum} chars)"
	echo "$sum  $GOROOT_TMP/$tarball" | sha256sum -c - >>"${LOGFILE:-/dev/null}" 2>&1 ||
		die "Go toolchain checksum mismatch — refusing to build"
	step_ok "Go $ver checksum verified"
	tar -C "$GOROOT_TMP" -xzf "$GOROOT_TMP/$tarball"
	PATH="$GOROOT_TMP/go/bin:$PATH"
	export PATH
	GOTOOLCHAIN=local
	export GOTOOLCHAIN # do not let go fetch a different one
	step_ok "Go $ver ready"
}

BUILD_SWAP=/var/lib/outhaul-build.swap

# Offers a temporary build swapfile when RAM+swap is under 2 GiB.
maybe_add_swap() { # mem_kb swap_kb
	need_swap "$1" "$2" || return 0
	note "low memory — the Go build may be OOM-killed without extra swap"
	ask_yes_no "  Create a temporary 2 GB swapfile for the build?" y || return 0
	[ -e "$BUILD_SWAP" ] && return 0
	spinner_start "creating build swapfile"
	# Mark now so cleanup removes the file even if swapon fails partway through.
	SWAP_ADDED=1
	set +e
	{
		fallocate -l 2G "$BUILD_SWAP" 2>/dev/null || dd if=/dev/zero of="$BUILD_SWAP" bs=1M count=2048
		chmod 600 "$BUILD_SWAP" && mkswap "$BUILD_SWAP" && swapon "$BUILD_SWAP"
	} >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	# Not fatal: continue even if swap couldn't be enabled (the build may just be tight).
	[ "$rc" -eq 0 ] || note "could not enable build swap — continuing without it"
}

# Removes only the swapfile we created.
remove_build_swap() {
	[ "${SWAP_ADDED:-0}" = 1 ] || return 0
	swapoff "$BUILD_SWAP" 2>/dev/null || true
	rm -f "$BUILD_SWAP"
	SWAP_ADDED=0
}

# Clones the repo (or uses --from-checkout dir). Prints the source dir via SRC_DIR.
fetch_source() {
	if [ "${FROM_CHECKOUT:-0}" = 1 ]; then
		SRC_DIR=$(cd "$CHECKOUT_DIR" && pwd)
		[ -f "$SRC_DIR/go.mod" ] || die "--from-checkout: no go.mod in $SRC_DIR"
		step_ok "using local checkout $SRC_DIR"
		return
	fi
	SRC_DIR=$(mktemp -d)
	spinner_start "cloning outhaul"
	set +e
	git clone --depth 1 "$OUTHAUL_REPO" "$SRC_DIR" >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	[ "$rc" -eq 0 ] || die "could not clone $OUTHAUL_REPO — see ${LOGFILE:-the install log}"
}

# Pure: the -ldflags value that stamps the build for the in-app updater.
build_ldflags() { # commit repo local(0|1)
	pkg=github.com/outhaul-dev/outhaul/internal/update
	out="-X $pkg.commit=$1 -X $pkg.repo=$2"
	[ "$3" = 1 ] && out="$out -X $pkg.local=true"
	printf '%s\n' "$out"
}

# Builds ./outhaul in SRC_DIR. Streams go build output to the log; shows a
# spinner (progress bar is best-effort since `go build` has no clean %).
build_binary() {
	# spinner_start runs in THIS shell (not the subshell) so cleanup can see SPIN_PID,
	# and set +e keeps a failed build from aborting before spinner_stop + die.
	spinner_start "building outhaul (this can take a few minutes)"
	set +e
	c=$(git -C "$SRC_DIR" rev-parse HEAD 2>/dev/null)
	l=0
	if [ "${FROM_CHECKOUT:-0}" = 1 ] && [ -n "$(git -C "$SRC_DIR" status --porcelain 2>/dev/null)" ]; then l=1; fi
	(cd "$SRC_DIR" && GOFLAGS=-buildvcs=false go build -ldflags "$(build_ldflags "$c" "${OUTHAUL_REPO:-}" "$l")" -o outhaul .) >>"${LOGFILE:-/dev/null}" 2>&1
	rc=$?
	set -e
	spinner_stop "$rc"
	{ [ "$rc" -eq 0 ] && [ -x "$SRC_DIR/outhaul" ]; } || die "build failed — see ${LOGFILE:-the install log}"
	step_ok "binary built"
}

# Pure: does PUBLIC_IP appear in the resolved-IP set?
domain_ip_matches() { # public_ip resolved_ips
	pub=$1
	# shellcheck disable=SC2086 # intentional word-splitting of the resolved-IP set into positional args
	set -- $2
	[ "$#" -gt 0 ] || return 1
	for ip in "$@"; do [ "$ip" = "$pub" ] && return 0; done
	return 1
}

host_public_ip() {
	curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null ||
		curl -fsS --max-time 5 https://ifconfig.me 2>/dev/null || true
}

# Space-separated A records for a name, using whatever resolver tool exists.
resolve_a() { # name
	if command -v getent >/dev/null 2>&1; then
		getent ahostsv4 "$1" 2>/dev/null | awk '{print $1}' | sort -u | paste -sd' ' -
	else
		host "$1" 2>/dev/null | awk '/has address/{print $NF}' | paste -sd' ' -
	fi
}

port_in_use() { # port
	if command -v ss >/dev/null 2>&1; then
		ss -ltn 2>/dev/null | awk '{print $4}' | grep -qE "[:.]$1\$"
	else netstat -ltn 2>/dev/null | awk '{print $4}' | grep -qE "[:.]$1\$"; fi
}

# Warns (does not hard-fail) about DNS/port issues before choosing ACME.
acme_preflight() { # domain
	dom=$1
	pub=$(host_public_ip)
	ips=$(resolve_a "$dom")
	note "this server's public IP: ${pub:-unknown}"
	note "$dom resolves to: ${ips:-<nothing>}"
	if [ -n "$pub" ] && ! domain_ip_matches "$pub" "$ips"; then
		step_fail "$dom does not point at this server"
		note "create a DNS A record:  $dom  A  $pub"
		ask_yes_no "  Continue with Let's Encrypt anyway?" n ||
			die "fix DNS, then re-run the installer"
	else
		step_ok "$dom points at this server"
	fi
	for p in 80 443; do
		port_in_use "$p" && step_fail "port $p already in use — Traefik may fail to bind" || true
	done
}

# Prints the distinct TCP ports listening on a non-loopback address, read
# from `ss -ltnp` output on stdin (a header line is tolerated), sorted and
# space separated. These are what a freshly enabled ufw would block. Ports
# Docker publishes (docker-proxy, e.g. Traefik's 80/443) bypass ufw.
ss_listen_ports() {
	awk '$1=="LISTEN" {
		if ($0 ~ /"docker-proxy"/) next
		a=$4; p=a; sub(/.*:/, "", p); sub(/:[^:]*$/, "", a); sub(/%.*/, "", a)
		if (a ~ /^127\./ || a=="[::1]" || a=="::1") next
		print p }' | sort -nu | paste -sd' ' -
}

# Prints the ports in $1 that do not appear in $2 (both space separated).
ports_not_in() { # ports exclude
	_out=''
	# shellcheck disable=SC2086 # intentional word-splitting of the port list
	for _p in $1; do
		case " $2 " in *" $_p "*) ;; *) _out="$_out $_p" ;; esac
	done
	printf '%s' "${_out# }"
}

listening_ports() {
	command -v ss >/dev/null 2>&1 || return 0
	ss -ltnp 2>/dev/null | ss_listen_ports
}

# Prints the listening ports that enabling ufw would newly block. The admin
# port is left out: it is meant to be firewalled, and Traefik reaches it
# over Outhaul's bridge (see apply_firewall).
ufw_would_block() { # listening opening adminport
	ports_not_in "$1" "$2 $3"
}

# Prints the host interface of a Docker network from
# `docker network inspect -f '{{.Id}} {{index .Options "com.docker.network.bridge.name"}}'`
# on stdin. Outhaul names its network's bridge after the network; an older
# network has Docker's default br-<first 12 of the id>. With no network yet,
# prints the name Outhaul will give it.
bridge_from_inspect() { # network
	read -r _id _bridge || {
		printf '%s\n' "$1"
		return 0
	}
	case "$_bridge" in
	'' | '<no value>') printf 'br-%.12s\n' "$_id" ;;
	*) printf '%s\n' "$_bridge" ;;
	esac
}

network_bridge() { # network
	docker network inspect "$1" -f '{{.Id}} {{index .Options "com.docker.network.bridge.name"}}' 2>/dev/null |
		bridge_from_inspect "$1"
}

ufw_active() { ufw status 2>/dev/null | grep -q '^Status: active'; }

# Opens the given port set with ufw. CRITICAL: `ufw allow` every port
# (especially SSH/22) BEFORE `ufw enable`, so the running session survives.
# Traefik reaches the admin UI on the host, arriving over Outhaul's Docker
# bridge, and ufw drops that like any other inbound traffic: allow the admin
# port from that bridge only. It is allowed in every mode, so publishing the
# admin UI later (a public URL, a tunnel) needs no firewall change.
apply_firewall() { # ports (space separated, must include 22) bridge adminport
	ports=$1
	bridge=$2
	adminport=$3
	if ! command -v ufw >/dev/null 2>&1; then
		spinner_start "installing ufw"
		set +e
		{ apt-get update -qq && apt-get install -y -qq ufw; } >>"${LOGFILE:-/dev/null}" 2>&1
		rc=$?
		set -e
		spinner_stop "$rc"
		# Not fatal: skip firewalling rather than abort the whole install.
		[ "$rc" -eq 0 ] || {
			note "could not install ufw — skipping firewall (open ports manually)"
			return 0
		}
	fi
	# shellcheck disable=SC2086 # intentional word-splitting of the space-separated port list
	for p in $ports; do
		ufw allow "$p"/tcp >>"${LOGFILE:-/dev/null}" 2>&1 || true
	done
	ufw allow in on "$bridge" to any port "$adminport" proto tcp >>"${LOGFILE:-/dev/null}" 2>&1 || true
	# --force avoids the interactive "proceed?" prompt; SSH is already allowed above.
	ufw --force enable >>"${LOGFILE:-/dev/null}" 2>&1 || true
	step_ok "firewall: opened $ports (SSH preserved)"
	note "admin port $adminport: allowed from Outhaul's Docker bridge ($bridge) only, so Traefik can serve it"
	note "open more later with: ufw allow <port>"
}

# Carry legacy slipway state across the rename (mirrors old install.sh).
migrate_slipway() {
	if [ -d /var/lib/slipway ] && [ ! -e /var/lib/outhaul ]; then
		systemctl stop outhaul 2>/dev/null || true
		mv /var/lib/slipway /var/lib/outhaul
		[ -f /var/lib/outhaul/slipway.db ] && mv /var/lib/outhaul/slipway.db /var/lib/outhaul/outhaul.db
		step_ok "migrated /var/lib/slipway -> /var/lib/outhaul"
	fi
	rm -f /usr/local/bin/slipway
}

ensure_service_user() {
	if ! id outhaul >/dev/null 2>&1; then
		nologin=$(command -v nologin || echo /usr/sbin/nologin)
		useradd --system --home-dir /var/lib/outhaul --create-home --shell "$nologin" outhaul
		step_ok "created system user outhaul"
	fi
	usermod -aG docker outhaul
}

install_binary() {
	install -m 0755 "$SRC_DIR/outhaul" /usr/local/bin/outhaul
	step_ok "installed /usr/local/bin/outhaul"
}

# Installs the systemd unit shipped in the repo and (re)starts the service.
install_service() {
	install -m 0644 "$SRC_DIR/deploy/outhaul.service" /etc/systemd/system/outhaul.service
	systemctl daemon-reload
	if systemctl is-active --quiet outhaul; then
		systemctl restart outhaul
	else systemctl enable --now outhaul; fi
	step_ok "outhaul service started"
}

# Copies src to dest by a temp file and rename, so a process that has dest
# open or is running it keeps the old file: a new inode, never a rewrite.
install_atomic() { # src dest mode
	rm -f "$2.new" || return 1
	cp "$1" "$2.new" || return 1
	chmod "$3" "$2.new" || return 1
	mv -f "$2.new" "$2"
}

# Runs a command inside dir, a directory the outhaul user owns, so that the
# command's relative names land in it: in a subshell whose working directory
# is dir itself, checked to be where it should be and not reached through a
# symlink. Renaming the path afterwards does not move the command elsewhere.
# Fails without running the command when dir is not that directory.
in_real_dir() { # dir command...
	(
		_dir=$1
		shift
		cd "$_dir" 2>/dev/null || exit 1
		[ "$(pwd -P)" = "$(cd "$(dirname "$_dir")" && pwd -P)/$(basename "$_dir")" ] || exit 1
		"$@"
	)
}

# Installs the root updater that Settings > Updates drives: the script and
# the installer it reuses, the two systemd units, the updater's own
# directory, and the directory Outhaul and the updater share. The paths are
# overridable for tests, and the updater itself calls this from a new tree
# after a healthy update.
install_updater() { # src_dir
	_lib=${LIB_DIR:-/usr/local/lib/outhaul}
	_units=${UNIT_DIR:-/etc/systemd/system}
	_upd=${UPDATE_DIR:-/var/lib/outhaul/update}
	_work=${WORK_DIR:-/var/lib/outhaul-updater}
	mkdir -p "$_lib" "$_units" || return 1
	install_atomic "$1/deploy/update.sh" "$_lib/update.sh" 0755 || return 1
	install_atomic "$1/deploy/bootstrap.sh" "$_lib/bootstrap.sh" 0644 || return 1
	install_atomic "$1/deploy/outhaul-update.path" "$_units/outhaul-update.path" 0644 || return 1
	install_atomic "$1/deploy/outhaul-update.service" "$_units/outhaul-update.service" 0644 || return 1
	# The updater's own: its rollback copy, temp files and log. Outhaul may
	# open the log in it, not list or change it.
	mkdir -p "$_work" || return 1
	chgrp outhaul "$_work" || return 1
	chmod 0710 "$_work" || return 1
	# The update directory is in outhaul's data dir: only a directory, not a
	# symlink, is set up there.
	if [ -L "$_upd" ] || { [ -e "$_upd" ] && [ ! -d "$_upd" ]; }; then
		step_fail "$_upd is not a directory"
		return 1
	fi
	if [ ! -d "$_upd" ]; then mkdir -p "$_upd" || return 1; fi
	in_real_dir "$_upd" set_up_update_dir "$_work" || return 1
	systemctl daemon-reload || return 1
	systemctl enable --now outhaul-update.path || return 1
	step_ok "installed the updater"
}

# Run by install_updater inside the update directory: makes it outhaul's,
# 0700, with the marker that tells Outhaul the updater is installed, made in
# the updater's directory and renamed in.
set_up_update_dir() { # work_dir
	chmod 0700 . || return 1
	chown -h outhaul:outhaul . || return 1
	_m=$(mktemp "$1/.updater.XXXXXX") || return 1
	if printf '1\n' >"$_m" && chmod 0644 "$_m" && mv -fT "$_m" updater; then
		return 0
	fi
	rm -f "$_m"
	return 1
}

# The installer's call: the updater is optional, so a failure must not stop
# the firewall, ingress and setup steps that follow.
setup_updater() { # src_dir
	if ! install_updater "$1"; then
		step_fail "could not install the updater"
		note "updating from the UI stays unavailable; re-run the installer to try again"
	fi
}

# The admin UI's port, from an OUTHAUL_LISTEN_ADDR-style ":8080".
admin_port() { # listen_addr
	addr=${1:-:8080}
	printf '%s\n' "${addr##*:}"
}

# Local admin URL to probe.
admin_health_url() { # listen_addr
	printf 'http://127.0.0.1:%s/\n' "$(admin_port "$1")"
}

# The host part of a URL: no scheme, port or path.
url_host() { # url
	h=${1#*://}
	h=${h%%/*}
	printf '%s\n' "${h%%:*}"
}

# Extracts the one-time setup URL from a stream of journald lines: the
# newest "open: URL" hint, since a re-run restarts the service, which prints
# a new token. With a public URL, that line holds the public one.
extract_setup_url() {
	grep -oE 'open: https?://[^ ]+/setup\?token=[A-Za-z0-9_-]+' | tail -1 | sed 's/^open: //'
}

# The setup URL to open over an SSH tunnel to the admin port.
local_setup_url() { # setup_url adminport
	printf 'http://127.0.0.1:%s/setup?token=%s\n' "$2" "${1##*token=}"
}

# Polls the admin endpoint up to ~30s. Returns 0 when it answers with ANY
# HTTP response (no -f: a pre-setup redirect/403 still means "reachable").
wait_healthy() { # url
	url=$1
	i=0
	spinner_start "waiting for outhaul to answer"
	while [ "$i" -lt 30 ]; do
		if curl -sS --max-time 2 -o /dev/null "$url" 2>/dev/null; then
			spinner_stop 0
			return 0
		fi
		sleep 1
		i=$((i + 1))
	done
	spinner_stop 1
	return 1
}

# Polls the admin UI's /healthz through Traefik, the way a browser reaches it
# under the public URL, for up to ~60s: Traefik may still be starting. Only a
# 200 counts (-f): a 404 is Traefik without the admin route, a 502/504 is
# Traefik unable to reach the admin port. -k: the certificate may not be
# issued yet.
wait_public_healthy() { # host
	host=$1
	i=0
	spinner_start "checking the admin UI at https://$host"
	while [ "$i" -lt 20 ]; do
		if curl -fsSk --max-time 2 -o /dev/null --resolve "$host:443:127.0.0.1" "https://$host/healthz" 2>/dev/null; then
			spinner_stop 0
			return 0
		fi
		sleep 1
		i=$((i + 1))
	done
	spinner_stop 1
	return 1
}

# Final boxed summary + confetti. Args passed as positional data. public is
# the check through Traefik (Let's Encrypt mode): 0 ok, 1 failed, '' not run.
# ADMIN_PORT and BRIDGE come from main.
completion_screen() { # mode url ports setup_url healthy(0/1) localca(0/1) public(0/1/'')
	mode=$1
	url=$2
	ports=$3
	setup=$4
	healthy=$5
	localca=${6:-0}
	public=${7:-}
	port=${ADMIN_PORT:-8080}
	bridge=${BRIDGE:-outhaul}
	printf '\n'
	hr
	_c '1;32'
	printf '  Outhaul is installed\n'
	_c 0
	if [ "$healthy" != 0 ]; then
		step_fail "admin UI did not answer yet (check: journalctl -u outhaul)"
	elif [ "$public" = 0 ]; then
		step_ok "Traefik serves the admin UI at $url (checked from this server)"
	elif [ "$public" = 1 ]; then
		step_fail "admin UI not answering at $url yet"
		note "Traefik may still be starting or getting a certificate (check: docker logs outhaul-traefik)"
		note "with ufw on, Traefik also needs: ufw allow in on $bridge to any port $port proto tcp"
	else
		step_ok "admin UI reachable"
	fi
	[ -n "$ports" ] && note "firewall: $ports open"
	# The firewall never opens the admin port, and only Let's Encrypt mode
	# routes the admin UI through Traefik — everyone else needs a tunnel.
	if [ -n "$ports" ] && [ "$mode" != a ]; then
		note "admin UI (:$port) is firewalled — reach it over SSH: ssh -L $port:127.0.0.1:$port you@this-server, then open http://127.0.0.1:$port"
	fi
	case "$mode" in
	a) note "HTTPS: Let's Encrypt configured for $url" ;;
	b)
		_c '1;33'
		printf '  → Finish Cloudflare Tunnel: log in, then paste your connector token in Settings → Tunnel\n'
		_c 0
		;;
	c) if [ "$localca" = 1 ]; then
		note "HTTPS: built-in local CA — install the root on your devices: outhaul ca root > outhaul-ca.pem (or download /ca.pem from the admin UI). See docs/LOCAL-CA.md."
	else
		note "admin UI on :8080 — set OUTHAUL_PUBLIC_URL + OUTHAUL_ACME_EMAIL later for HTTPS"
	fi ;;
	esac
	if [ -n "$setup" ]; then
		printf '\n  Open this one-time setup URL to create your admin account:\n'
		_c '1;36'
		printf '    %s\n' "$setup"
		_c 0
		# The public check runs on this server: DNS or a cloud firewall can
		# still stand between a browser and Traefik.
		if [ "$mode" = a ]; then
			note "if it does not open: ssh -L $port:127.0.0.1:$port you@this-server, then open $(local_setup_url "$setup" "$port")"
		fi
	else
		note "find the setup URL with: journalctl -u outhaul | grep -i setup"
	fi
	# Confetti flourish (skipped in plain mode).
	if [ "${COLOR:-0}" -ge 1 ] && [ "${UNICODE:-0}" = 1 ]; then
		printf '\n  '
		for s in '✦' '✧' '·' '✦' '✧' '·' '✦' '✧'; do printf '%s ' "$s"; done
		printf '\n'
	fi
	hr
}

LOGFILE=/var/log/outhaul-install.log
VERBOSE=0
FROM_CHECKOUT=0
CHECKOUT_DIR=.

parse_args() {
	while [ "$#" -gt 0 ]; do
		case "$1" in
		--verbose) VERBOSE=1 ;;
		--from-checkout)
			FROM_CHECKOUT=1
			CHECKOUT_DIR=${2:-.}
			shift
			;;
		-h | --help)
			printf 'usage: bootstrap.sh [--verbose] [--from-checkout DIR]\n'
			exit 0
			;;
		*) die "unknown option: $1" ;;
		esac
		shift
	done
}

cleanup() {
	if [ -n "${SPIN_PID:-}" ]; then kill "$SPIN_PID" 2>/dev/null || true; fi
	remove_build_swap || true
	if [ "${FROM_CHECKOUT:-0}" != 1 ] && [ -n "${SRC_DIR:-}" ]; then rm -rf "$SRC_DIR"; fi
	if [ -n "${GOROOT_TMP:-}" ]; then rm -rf "$GOROOT_TMP"; fi
}

# Ingress-mode menu. Sets MODE (a/b/c), PUBLIC_URL, ACME_EMAIL, LOCAL_CA (0/1).
choose_ingress() {
	LOCAL_CA=0
	printf '\n  How should apps be reachable?\n'
	printf '    1) Public domain + automatic HTTPS (Let'\''s Encrypt)\n'
	printf '    2) Cloudflare Tunnel (no public IP / ports needed)\n'
	printf '    3) Local only (optional HTTPS from a built-in local CA)\n'
	choice=$(ask_value "  Choose 1/2/3:" 1)
	case "$choice" in
	2)
		MODE=b
		PUBLIC_URL=''
		ACME_EMAIL=''
		;;
	3)
		MODE=c
		PUBLIC_URL=''
		ACME_EMAIL=''
		# || true: a "no" answer must not abort under set -e
		ask_yes_no "  Enable HTTPS with a local certificate authority?" y && LOCAL_CA=1 || true
		;;
	*)
		MODE=a
		PUBLIC_URL=$(ask_value "  Public URL (e.g. https://paas.example.com):" '')
		dom=${PUBLIC_URL#*://}
		dom=${dom%%/*}
		acme_preflight "$dom"
		ACME_EMAIL=$(ask_value "  Email for Let's Encrypt:" '')
		;;
	esac
}

main() {
	parse_args "$@"
	: >"$LOGFILE" 2>/dev/null || LOGFILE=/dev/null
	if [ "$VERBOSE" = 1 ]; then LOGFILE=/dev/stderr; fi
	trap cleanup EXIT INT TERM
	open_prompt_fd "$0"

	init_ui
	hero
	preflight

	choose_ingress
	PUBLIC_URL=$(normalize_public_url "$PUBLIC_URL")

	GITPORT=$(normalize_git_port "$(ask_value "  Git-push-to-deploy port ('none' to disable):" 2222)")
	if [ -n "$GITPORT" ]; then SSH_ADDR=":$GITPORT"; else SSH_ADDR=''; fi

	if ask_yes_no "  Install Nixpacks (needed for auto-detected builds)?" y; then WANT_NIXPACKS=1; else WANT_NIXPACKS=0; fi
	if ask_yes_no "  Configure the firewall (ufw) now?" y; then WANT_FW=1; else WANT_FW=0; fi

	ensure_docker
	ensure_git
	if [ "$WANT_NIXPACKS" = 1 ]; then ensure_nixpacks; fi

	fetch_source
	GO_VER=$(go_version_from_gomod "$SRC_DIR/go.mod")
	maybe_add_swap "${MEM_KB:-0}" "${SWAP_KB:-0}"
	install_go_toolchain "$GO_VER"
	build_binary
	remove_build_swap

	migrate_slipway
	ensure_service_user
	install_binary
	if [ ! -f /etc/outhaul.env ]; then
		write_env_file /etc/outhaul.env "$MODE" "$PUBLIC_URL" "$ACME_EMAIL" "$SSH_ADDR" "${LOCAL_CA:-0}"
		step_ok "wrote /etc/outhaul.env"
	else
		note "/etc/outhaul.env exists — left unchanged"
	fi
	install_service
	setup_updater "$SRC_DIR"

	if [ -n "${GOROOT_TMP:-}" ]; then
		if ask_yes_no "  Remove the downloaded Go toolchain (~150 MB)?" y; then
			rm -rf "$GOROOT_TMP"
			GOROOT_TMP=''
			step_ok "removed Go toolchain"
		fi
	fi

	PORTS=''
	ADMIN_PORT=$(admin_port "${OUTHAUL_LISTEN_ADDR:-:8080}")
	BRIDGE=$(network_bridge outhaul)
	if [ "$WANT_FW" = 1 ]; then
		PORTS=$(derive_firewall_ports "$MODE" "$GITPORT" "${LOCAL_CA:-0}")
		# Preserve the port of the admin's LIVE SSH session too, in case sshd
		# listens somewhere other than 22 — otherwise enabling ufw locks them out.
		if [ -n "${SSH_CONNECTION:-}" ]; then
			assh=${SSH_CONNECTION##* }
			case " $PORTS " in *" $assh "*) ;; *) [ -n "$assh" ] && PORTS="$PORTS $assh" ;; esac
		fi
		printf '  Firewall will open (SSH always preserved): %s\n' "$PORTS"
		# On a host that already serves other things, enabling ufw would cut
		# them off: say which ports, and default to leaving the firewall alone.
		fw_default=y
		if ! ufw_active; then
			blocked=$(ufw_would_block "$(listening_ports)" "$PORTS" "$ADMIN_PORT")
			if [ -n "$blocked" ]; then
				step_fail "ufw is inactive; enabling it would also block ports listening now: $blocked"
				note "containers with published ports are not affected; open others with: ufw allow <port>"
				fw_default=n
			fi
		fi
		if ask_yes_no "  Proceed?" "$fw_default"; then
			apply_firewall "$PORTS" "$BRIDGE" "$ADMIN_PORT"
		else PORTS=''; fi
	fi

	HURL=$(admin_health_url "${OUTHAUL_LISTEN_ADDR:-:8080}")
	if wait_healthy "$HURL"; then HEALTHY=0; else HEALTHY=1; fi
	# Let's Encrypt mode serves the admin UI through Traefik, with the
	# firewall in between: check the way a browser reaches it too.
	PUBLIC=''
	if [ "$MODE" = a ] && [ -n "$PUBLIC_URL" ] && [ "$HEALTHY" = 0 ]; then
		if wait_public_healthy "$(url_host "$PUBLIC_URL")"; then PUBLIC=0; else PUBLIC=1; fi
	fi
	# Only the service's current run: a re-run restarted it with a new token,
	# and an earlier run's hint is stale. -b is the fallback without systemd's
	# invocation ID.
	inv=$(systemctl show -p InvocationID --value outhaul 2>/dev/null || true)
	if [ -n "$inv" ]; then
		SETUP=$(journalctl _SYSTEMD_INVOCATION_ID="$inv" --no-pager 2>/dev/null | extract_setup_url)
	else
		SETUP=$(journalctl -u outhaul -b --no-pager 2>/dev/null | extract_setup_url)
	fi

	completion_screen "$MODE" "$PUBLIC_URL" "$PORTS" "$SETUP" "$HEALTHY" "${LOCAL_CA:-0}" "$PUBLIC"
}

